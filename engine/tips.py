"""Reflective interpretation + evidence-informed parenting tip bank.

Design rules (non-negotiable):
* NO diagnostic labels, NO "hidden feelings" claims.
* Reflections are phrased as possibilities ("قد يعكس…") and always paired with
  a question for the parent to verify through observation over time.
* Tips are classic positive-parenting practices (play-based learning,
  co-regulation, routines) keyed by the parent-reported mood + age band.
"""
from typing import Any, Dict, List, Tuple

# ── Reflective readings of OBJECTIVE drawing metrics ──────────────────────
def drawing_reflections(m: Dict[str, Any]) -> List[str]:
    refl: List[str] = []
    pal = m.get("palette") or []
    warm = 0
    cool = 0
    for c in pal[:4]:
        r = int(c["rgb"][1:3], 16); g = int(c["rgb"][3:5], 16); b = int(c["rgb"][5:7], 16)
        if r > b + 30: warm += c["share"]
        if b > r + 30: cool += c["share"]
    if warm > 0.5:
        refl.append("الألوان الدافئة (أحمر/برتقالي/أصفر) مسيطرة في هذه الرسمة — أحياناً تعكس حماساً وطاقة وأحياناً انفعالاً لطيفاً.")
    if cool > 0.5:
        refl.append("الألوان الباردة (أزرق/أخضر) مسيطرة — غالباً تعكس هدوءاً أو تركيزاً لدى بعض الأطفال.")
    ink = m.get("ink_coverage") or 0
    if ink > 0.45:
        refl.append("تغطية حبر مرتفعة على الصفحة — قد تعكس انشغالاً شديداً بالنشاط وثقة في الحركة.")
    elif ink < 0.08:
        refl.append("تغطية حبر خفيفة — قد تكون مرحلة استكشاف (ملاحظة القلم أو الرقبة) أو مزاج صامت اليوم.")
    thirds = m.get("ink_thirds") or []
    if thirds and thirds[2] > 0.55:
        refl.append("تركّز الحبر في الثلث السفلي للورقة — بعض المربين يربطون ذلك بالأرضية والأمان في بعض الرسومات؛ يُقرأ مع رسمات قادمة وليس وحده.")
    strokes = m.get("stroke_density") or 0
    if strokes > 0.35:
        refl.append("كثافة خطوط عالية في منطقة الوسط — إشارة لحركة قلم نشطة (طاقة أو تركيز).")
    elif 0 < strokes < 0.08:
        refl.append("خطوط متباعدة قليلاً — قد تتدرب على التحكم بالمقلمة.")
    if not refl:
        refl.append("رسومات اليوم بألوان متوازنة وتعبير متوسط — سجّلها وراقب النمط عبر أسبوع.")
    refl.append("🎓 قاعدة MIRA: الرسمة الواحدة لا تُقرأ وحدها — القوة في النمط عبر الزمن. اسأل طفلك عن رسمته فكلماته أهم من تفسيراتنا.")
    return refl


